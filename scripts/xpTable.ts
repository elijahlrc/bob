/**
 * The level curve's table (DESIGN.md §5.4): the experience a map holds at each area level, with every monster on it killed
 * (the owner, 2026-10-30), so a level costs one map at the character's level. The maps are made as the game makes them, from
 * the offers it rolls (`rollOffers`, `planFor`): their themes, types, biomes, densities and the early crowd. Nothing is played.
 * A Crawl's three maps count as one, as they take one level. Averaged over the seeds and the offers at each area level,
 * smoothed over ±2 levels, and written to src/data/mapXp.ts.
 *
 *   npm run xp:emit -- [--seeds 20]
 */
import { writeFileSync } from 'node:fs';
import { buildMonster } from '../src/calc/monster';
import { CRAWL_SEGMENTS } from '../src/data/mapTypes';
import { rollOffers } from '../src/run/offers';
import { newRun, planFor } from '../src/run/run';

const arg = (k: string, d: string) => {
  const i = process.argv.indexOf(`--${k}`);
  return i >= 0 ? process.argv[i + 1] : d;
};
const seeds = Number(arg('seeds', '20'));
const LEVELS = 100;

const sum = new Array<number>(LEVELS + 3).fill(0);
const count = new Array<number>(LEVELS + 3).fill(0);
for (let seed = 1; seed <= seeds; seed++) {
  // The class does not change the maps.
  const run = newRun('vanguard', seed);
  for (let map = 1; map <= LEVELS; map++) {
    run.map = map;
    run.offers = rollOffers(run.seed, map);
    for (const offer of run.offers) {
      if (offer.kind !== 'map') continue;
      let xp = 0;
      const segments = offer.type === 'crawl' ? CRAWL_SEGMENTS : 1;
      for (let s = 0; s < segments; s++) {
        const plan = planFor(run, offer, s);
        let mapXp = 0;
        for (const mon of plan.pop.monsters) mapXp += buildMonster(mon.spec).xp;
        xp += mapXp * plan.xpMult;
      }
      const at = Math.min(LEVELS + 2, Math.max(1, offer.areaLevel));
      sum[at] += xp;
      count[at]++;
    }
  }
  process.stdout.write(`\rseed ${seed}/${seeds}`);
}
console.log();

// The mean at each level (a level no offer reached takes its neighbour's), then smoothed over ±2 levels.
const mean: number[] = [];
for (let l = 1; l <= LEVELS; l++) mean.push(count[l] ? sum[l] / count[l] : 0);
for (let i = 0; i < LEVELS; i++) if (!mean[i]) mean[i] = mean[i - 1] ?? mean.find((v) => v) ?? 0;
const smooth = mean.map((_, i) => {
  let s = 0;
  let n = 0;
  for (let j = Math.max(0, i - 2); j <= Math.min(LEVELS - 1, i + 2); j++) {
    s += mean[j];
    n++;
  }
  return Math.round(s / n);
});

const body = [
  '// Generated by `npm run xp:emit` (scripts/xpTable.ts, DESIGN.md §5.4): the experience of every monster on a map at each',
  `// area level (index 0 = level 1), all of them killed, over the offers the game rolls (${seeds} seeds), smoothed over ±2 levels.`,
  `export const MAP_XP: number[] = ${JSON.stringify(smooth)};`,
  '',
].join('\n');
writeFileSync(new URL('../src/data/mapXp.ts', import.meta.url), body);
console.log('wrote src/data/mapXp.ts');
for (const l of [1, 5, 10, 13, 20, 30, 50, 75, 100]) console.log(`level ${l}: ${smooth[l - 1]}`);
