/**
 * Bakes the passive tree (iteration 8, the user: the layout may take seconds to build as long as it is done once, at build time, and not
 * in the browser). Lays the tree out from the charter and the plan (`layout.ts`) and writes the finished nodes to
 * `src/data/tree/treeBaked.ts`, which `getTree()` reads: the game does no layout at run time. Run it after anything that changes the tree
 * (the charter, the plan, roads, shapes, the clusters); the test that compares the file with a fresh layout fails until you do.
 *
 *   npm run tree:bake
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildLayoutTree } from '../../src/data/tree/layout';

const OUT = resolve(import.meta.dirname, '../../src/data/tree/treeBaked.ts');

const t0 = Date.now();
const built = buildLayoutTree();
if (built.dropped.length || built.unplaced.length) {
  console.error('the layout dropped roads or left clusters out:', built.dropped, built.unplaced);
  process.exit(1);
}
const json = JSON.stringify({ nodes: built.nodes, starts: built.starts });
// One string literal parsed once: far quicker for the compiler and the browser than a literal of 2,600 nodes.
const text = `/* Generated by \`npm run tree:bake\` (scripts/tree/bake.ts) from layout.ts. Do not edit. */
import type { Tree } from './types';

export const BAKED_TREE: Tree = JSON.parse(${JSON.stringify(json)}) as Tree;
`;
writeFileSync(OUT, text);
console.log(
  `baked ${built.nodes.length} nodes (${(json.length / 1024).toFixed(0)} KB) to ${OUT} in ${Date.now() - t0} ms`,
);
