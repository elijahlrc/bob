/**
 * The archetypes the growth plan measures tension with (docs/tree/design/G-growth.md §1, phase G0). Each one is a
 * player's wish list: how much a node's lines are worth to that build. They are a yardstick for walks through the
 * network, never a reason to place a node (CONSTRAINTS §14: the network is not designed from a list of builds).
 *
 * A line is keyed by its vocabulary function and its non-numeric arguments, as `lines.ts` writes them: `life`,
 * `eleDamage:cold`, `leechLife:attack`, `weaponDamage:sceptre`. `fn:*` matches every variant of a function. A node is
 * worth the sum of its lines' units (`Line.units`, the small node of the stat = 1) times the weight of each line's key.
 *
 * Weights, by convention: 1 a main want, 0.5 a want, 0.25 to 0.4 a nice-to-have. **Attribute lines are worth nothing**
 * here: they are the road's supply, reported beside each plan against the weapon's gear (`gear`), so the share of points
 * spent on nodes worth nothing (the tax) stays meaningful.
 *
 * `main` names the stat families reported one at a time, in their own terms; `pair` is the two reported together. They
 * are what the user reads; the weights only steer the allocator.
 */

export type Archetype = {
  id: string;
  /** What the player wants, in a line. */
  want: string;
  /** The class it starts as. */
  start: 'vanguard' | 'strider' | 'mystic' | 'reaver' | 'zealot' | 'shade';
  weights: Record<string, number>;
  /** Keystones it would take, with their worth in units. */
  keystones?: Record<string, number>;
  /** Stat families reported one at a time: label → keys. */
  main: Record<string, string[]>;
  /** Two labels of `main`, reported together. */
  pair: [string, string];
  /** What its weapon's gear asks for late in a run (reported against what a plan supplies). */
  gear?: { str?: number; dex?: number; int?: number };
};

