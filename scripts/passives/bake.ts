/**
 * Bakes the hand-written passive tree (src/data/passives) for the game: assembles every area, applies the editor's patch
 * (edits.json) and writes the finished nodes, starts and area names to `src/data/passives/baked.ts`, which `getTree()`
 * reads. The area files' design notes stay out of the game. Run it after any change to an area file, `lines.ts`, the
 * registry or the editor's patch; the test that compares the file with a fresh build fails until you do.
 *
 *   npm run passives:bake
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildAll } from '../../src/data/passives';

const OUT = resolve(import.meta.dirname, '../../src/data/passives/baked.ts');

const built = buildAll({ allowNew: false });
if (built.problems.length) {
  console.error('the tree has problems:\n  ' + built.problems.join('\n  '));
  process.exit(1);
}
const json = JSON.stringify(built.tree);
// One string literal parsed once, as the old tree's bake does: quicker for the compiler and the browser than a literal.
const text = `/* Generated by \`npm run passives:bake\` (scripts/passives/bake.ts) from the area files. Do not edit. */
import type { Tree } from '../tree/types';

export const PASSIVE_TREE: Tree = JSON.parse(${JSON.stringify(json)}) as Tree;
`;
writeFileSync(OUT, text);
console.log(
  `baked ${built.tree.nodes.length} nodes (${(json.length / 1024).toFixed(0)} KB) to ${OUT}`,
);
