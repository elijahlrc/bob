/**
 * Turns the reviewed gem decisions in docs/coverage/gems/*.json into src/data/gemsGen.ts and the matching lines of
 * docs/coverage/map.json. A decision carries the whole Bob definition (`def`, an ActiveGemDef or SupportGemDef) written
 * by hand from the 3.9-era numbers (`npm run coverage:gems -- --next 20`), and the defining-mechanic note. The generated
 * file is type-checked, so a typo in a decision stops the build.
 *
 *   npm run coverage:emit-gems
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { COVERAGE_DIR, key, loadReference } from './reference';

export type GemDecision = {
  /** The reference gem this is an analog of (its wiki name, "Support" included for supports). */
  ref: string;
  /** What the gem does and why it counts. */
  note: string;
  status?: 'covered' | 'partial';
  def: { kind: 'active' | 'support'; id: string; name: string } & Record<string, unknown>;
};

export const DECISIONS_DIR = resolve(COVERAGE_DIR, 'gems');
export const OUT = resolve(COVERAGE_DIR, '../../src/data/gemsGen.ts');

export function loadGemDecisions(): GemDecision[] {
  const out: GemDecision[] = [];
  try {
    for (const f of readdirSync(DECISIONS_DIR)
      .filter((x) => x.endsWith('.json'))
      .sort())
      out.push(...(JSON.parse(readFileSync(resolve(DECISIONS_DIR, f), 'utf8')) as GemDecision[]));
  } catch {
    /* none yet */
  }
  return out;
}

const HEADER = `import type { ActiveGemDef, SupportGemDef } from './gems';

/**
 * Gems of the coverage plan (C3 onward). Generated by scripts/coverage/emit-gems.ts from the decisions in
 * docs/coverage/gems/*.json: edit those, not this file. Every name and description is ours.
 */
`;

export async function renderGems(
  decisions: GemDecision[],
): Promise<{ text: string; entries: [string, { ref: string; status: string; note: string }][] }> {
  const ref = loadReference();
  const ids = new Set<string>();
  const entries: [string, { ref: string; status: string; note: string }][] = [];
  const actives: unknown[] = [];
  const supports: unknown[] = [];
  for (const d of decisions) {
    const r = ref.gems.find((g) => key(g.name) === key(d.ref));
    if (!r) throw new Error(`gem decision "${d.def.name}": no reference gem "${d.ref}"`);
    if (ids.has(d.def.id)) throw new Error(`duplicate gem id ${d.def.id}`);
    ids.add(d.def.id);
    if (d.def.kind !== r.kind)
      throw new Error(`gem "${d.def.name}": kind ${d.def.kind} but the reference is ${r.kind}`);
    (d.def.kind === 'active' ? actives : supports).push(d.def);
    entries.push([d.def.id, { ref: r.name, status: d.status ?? 'covered', note: d.note }]);
  }
  const lit = (xs: unknown[]) => JSON.stringify(xs, null, 2);
  const raw = `${HEADER}export const GEN_ACTIVE_GEMS: ActiveGemDef[] = ${lit(actives)};\n\nexport const GEN_SUPPORT_GEMS: SupportGemDef[] = ${lit(supports)};\n`;
  const text = await format(raw, { ...(await resolveConfig(OUT)), filepath: OUT });
  return { text, entries };
}

async function main(): Promise<void> {
  const { text, entries } = await renderGems(loadGemDecisions());
  writeFileSync(OUT, text);
  const mapPath = resolve(COVERAGE_DIR, 'map.json');
  const map = JSON.parse(readFileSync(mapPath, 'utf8')) as {
    gems: Record<string, unknown>;
    uniques: Record<string, unknown>;
  };
  for (const [id, e] of entries) map.gems[id] = e;
  writeFileSync(mapPath, JSON.stringify(map, null, 1) + '\n');
  console.log(`emitted ${entries.length} gems to ${OUT}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) void main();
