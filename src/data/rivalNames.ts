/** The longest a made-up name can be: for the tests that hold it within the table's 48. */
export const MAX_GENERATED_NAME =
  'The '.length +
  Math.max(...RIVAL_EPITHETS.map((s) => s.length)) +
  ' of the '.length +
  Math.max(...RIVAL_PLACES.map((s) => s.length));

/** A made-up name from a seed: the same seed gives the same name. */
export function generateName(seed: number): string {
  const rng = new Rng(seed).fork('rivalName');
  return `The ${rng.pick(RIVAL_EPITHETS)} of the ${rng.pick(RIVAL_PLACES)}`;
}
