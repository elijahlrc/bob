export type Glyph = { top: number; rows: string[]; w: number };

/** A glyph's rows, or null when the set has none for `ch`. */
export function parseGlyph(set: GlyphSet, ch: string): Glyph | null {
  const src = set[ch];
  if (src === undefined) return null;
  const [top, body] = src.split('|');
  const rows = body.split('/');
  return { top: Number(top), rows, w: Math.max(...rows.map((r) => r.length)) };
}

